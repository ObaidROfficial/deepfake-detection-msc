"""
Graphical installer for the OBI DeepFake Image Detector.

Runs as a normal Python script during development:

    python installer/installer.py

For distribution it is compiled to a standalone executable with PyInstaller
(see installer/build.py), which bundles a Python runtime so the end user needs
nothing pre-installed. The bundle stays small - around 20MB - because only
tkinter and the standard library are packaged. PyTorch and the other heavy
dependencies are fetched at install time into a virtual environment, which is
why the installer itself is not a 1.5GB download.

WHAT IT DOES
    1. Checks for a Python in the tested band (3.9 to 3.13), and offers to
       download and install the official 3.11.9 from python.org if the machine
       has nothing suitable
    2. Lets the user pick an install location
    3. Downloads the application from GitHub
    4. Creates a virtual environment and installs the CPU build of PyTorch
    5. Downloads the trained model weights from the GitHub release
    6. Creates a desktop shortcut
    7. Offers to launch immediately

The long work happens on a worker thread so the window stays responsive and
the progress bar actually moves.
"""

