    # -- installing Python ----------------------------------------------------
    def start_python_install(self):
        self.show_progress(f"Installing Python {PY_VERSION}",
                           "Downloading from python.org")
        threading.Thread(target=self._python_worker, daemon=True).start()
        self.after(80, self._drain)

    def _python_worker(self):
        """
        Download the official python.org installer and run it.

        Windows gets a silent per-user install so nothing needs administrator
        rights. macOS ships Python only as a system-wide .pkg, so there the
        user is prompted for their password through the standard macOS dialog.
        """
        import tempfile
        try:
            url, name = python_installer_url()
            tmp = Path(tempfile.mkdtemp(prefix="obi-python-"))
            dest = tmp / name

            self._base, self._span = 0, 55
            self._download(url, dest, f"Python {PY_VERSION}")

            self.progress(58, "Checking the download")
            expected = PY_MD5.get(name)
            actual = md5_of(dest)
            if expected and actual != expected:
                dest.unlink(missing_ok=True)
                raise RuntimeError(
                    "The downloaded Python installer does not match the "
                    "checksum published by python.org, so it has been deleted "
                    "without being run.\n\n"
                    f"expected  {expected}\n"
                    f"got       {actual}\n\n"
                    "This almost always means the download was interrupted or "
                    "corrupted. Try again on a stable connection.")
            self.log(f"  checksum ok ({actual})")

            self.progress(65, "Running the Python installer")
            self.log("\nThe Python installer is running. This can take a "
                     "minute with no visible activity.")

            if platform.system() == "Windows":
                # Per-user install: no UAC prompt, and PrependPath puts the new
                # interpreter on PATH for future sessions.
                proc = subprocess.run(
                    [str(dest), "/quiet", "InstallAllUsers=0", "PrependPath=1",
                     "Include_launcher=1", "Include_test=0", "Include_pip=1"],
                    capture_output=True, text=True, timeout=1800,
                )
                code = proc.returncode
                if code == 1602:
                    raise RuntimeError("The Python installation was cancelled.")
                if code == 3010:
                    self.log("  installer asks for a restart; continuing anyway")
                elif code != 0:
                    raise RuntimeError(
                        f"The Python installer exited with code {code}.")
            else:
                # installer(8) needs root. osascript raises the familiar macOS
                # password dialog rather than a terminal prompt nobody can see.
                script = (f'do shell script "installer -pkg \\"{dest}\\" '
                          f'-target /" with administrator privileges')
                proc = subprocess.run(["osascript", "-e", script],
                                      capture_output=True, text=True, timeout=1800)
                if proc.returncode != 0:
                    err = (proc.stderr or "").strip()
                    if "-128" in err or "User canceled" in err:
                        raise RuntimeError("The Python installation was cancelled.")
                    raise RuntimeError(err or "The Python installer failed.")

            self.progress(90, "Checking the installation")
            self.log("Looking for the new interpreter...")
            found = find_python()
            if not found:
                raise RuntimeError(
                    "Python appears to have installed, but this installer "
                    "cannot find it. Closing and reopening the installer "
                    "usually fixes this, because the new Python is only added "
                    "to PATH for programs started afterwards.")

            self.log(f"Found: {found}")
            self.progress(100, "Python is ready")
            shutil.rmtree(tmp, ignore_errors=True)
            self.log_queue.put(("py_done", found))

        except Exception as e:
            self.log(f"\nFAILED: {e}")
            self.log_queue.put(("py_error", e))

