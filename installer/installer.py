    def _launch(self):
        target = Path(self.install_dir.get())
        where = payload_dir(target)
        # child_env() matters more here than anywhere else: without it the
        # detector inherits this installer's TCL_LIBRARY and cannot find its
        # own Tcl. See the comment on _UNSAFE_TO_INHERIT.
        env = child_env()
        try:
            if IS_MAC:
                # Let Finder start the bundle, so it behaves exactly as it
                # will when the user opens it from Applications. Finder gives
                # the app a fresh environment, so nothing is inherited here.
                subprocess.Popen(["open", str(target)])
            elif IS_WINDOWS:
                launcher = where / "Launch Detector.bat"
                if launcher.exists():
                    subprocess.Popen(["cmd", "/c", "start", "", str(launcher)],
                                     cwd=where, env=env)
                else:
                    subprocess.Popen([str(where / "venv" / "Scripts" / "pythonw.exe"),
                                      str(where / "app.py")], cwd=where, env=env)
            else:
                subprocess.Popen([str(where / "venv" / "bin" / "python"),
                                  str(where / "app.py")], cwd=where, env=env)
        except Exception as e:
            messagebox.showerror("Could not launch", str(e))

    # -- worker -------------------------------------------------------------
    def log(self, msg):
        self.log_queue.put(("log", msg))

    def progress(self, pct, status=None):
        self.log_queue.put(("progress", (pct, status)))

    def start_install(self):
        target = Path(self.install_dir.get())
        if target.exists() and any(target.iterdir()):
            if not messagebox.askyesno(
                    "Folder not empty",
                    f"{target}\n\nalready contains files. Continue anyway?"):
                return
        self.show_progress()
        threading.Thread(target=self._install_worker, daemon=True).start()
        self.after(80, self._drain)

    def _drain(self):
        try:
            while True:
                kind, payload = self.log_queue.get_nowait()
                if kind == "log":
                    self.logbox.configure(state="normal")
                    self.logbox.insert("end", str(payload) + "\n")
                    self.logbox.see("end")
                    self.logbox.configure(state="disabled")
                elif kind == "progress":
                    pct, status = payload
                    self.bar["value"] = pct
                    if status:
                        self.status.configure(text=status)
                elif kind == "done":
                    self.show_finish(True)
                    return
                elif kind == "error":
                    self.show_finish(False, str(payload))
                    return
                elif kind == "py_done":
                    self.python_cmd = str(payload)
                    self.show_options()
                    return
                elif kind == "py_error":
                    self.show_python_failed(str(payload))
                    return
        except queue.Empty:
            pass
        self.after(80, self._drain)

    def _run(self, cmd, cwd=None):
        """Run a command, streaming output into the log."""
        self.log("$ " + " ".join(str(c) for c in cmd))
        p = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT, text=True, bufsize=1,
                             env=child_env())
        for line in p.stdout:
            if self.cancelled:
                p.kill()
                raise RuntimeError("Cancelled")
            line = line.rstrip()
            if line:
                self.log("  " + line[:110])
        p.wait()
        if p.returncode != 0:
            raise RuntimeError(f"Command failed ({p.returncode}): {' '.join(map(str, cmd))}")

    def _download(self, url, dest: Path, label: str):
        self.log(f"Downloading {label}...")
        def hook(blocks, bs, total):
            if total > 0:
                pct = min(100, blocks * bs * 100 // total)
                self.progress(self._base + pct * self._span // 100,
                              f"{label}  {pct}%")
        urllib.request.urlretrieve(url, dest, reporthook=hook)
        self.log(f"  saved {dest.name} ({dest.stat().st_size/1e6:.1f} MB)")

    def _install_worker(self):
        try:
            target = Path(self.install_dir.get())
            target.mkdir(parents=True, exist_ok=True)

            # On macOS the target is a .app bundle, so build the skeleton
            # first: the payload has to land inside Contents/Resources.
            if IS_MAC:
                where = make_app_bundle(target)
                self.log(f"Created application bundle: {target.name}")
            else:
                where = target

            # 1. Python. Normally already resolved on the welcome screen; this
            #    re-check is a safety net, not the main path.
            self._base, self._span = 0, 5
            self.progress(2, "Looking for Python")
            self.python_cmd = self.python_cmd or find_python()
            if not self.python_cmd:
                raise RuntimeError(
                    f"No suitable Python found (needs {PY_MIN[0]}.{PY_MIN[1]} "
                    f"to {PY_MAX[0]}.{PY_MAX[1]}).\n"
                    f"Install it from {PYTHON_DOWNLOAD} and run this again.")
            self.log(f"Using Python: {self.python_cmd}")

            # 2. Application files
            self._base, self._span = 5, 15
            self.progress(6, "Downloading application")
            zip_path = where / "_src.zip"
            self._download(SOURCE_ZIP, zip_path, "application files")
            self.log("Extracting...")
            with zipfile.ZipFile(zip_path) as z:
                z.extractall(where / "_extract")
            inner = next((where / "_extract").iterdir())

            copied, skipped = [], []
            for item in sorted(inner.iterdir()):
                if item.name not in RUNTIME_ITEMS:
                    skipped.append(item.name)
                    continue
                dst = where / item.name
                if dst.exists():
                    shutil.rmtree(dst) if dst.is_dir() else dst.unlink()
                shutil.move(str(item), str(dst))
                copied.append(item.name)

            # Icons, lifted out of installer/ so the install does not carry the
            # build tooling with it. app.png is what the application window
            # uses on macOS and Linux, .ico on Windows, .icns for the bundle.
            for icon in ("app.ico", "app.png", "app.icns"):
                src_icon = inner / "installer" / icon
                if not src_icon.exists():
                    continue
                if icon == "app.icns" and IS_MAC:
                    shutil.move(str(src_icon), str(target / "Contents" /
                                                   "Resources" / icon))
                else:
                    shutil.move(str(src_icon), str(where / icon))
                copied.append(icon)

            shutil.rmtree(where / "_extract", ignore_errors=True)
            zip_path.unlink(missing_ok=True)
            self.log(f"  installed {len(copied)} items")
            if skipped:
                self.log(f"  skipped (not needed to run): {', '.join(skipped)}")

            # 3. Virtual environment
            self._base, self._span = 20, 5
            self.progress(21, "Creating virtual environment")
            self._run([*python_argv(self.python_cmd), "-m", "venv", "venv"],
                      cwd=where)
            vpy = (where / "venv" / ("Scripts" if IS_WINDOWS else "bin") /
                   ("python.exe" if IS_WINDOWS else "python"))

            # 4. Dependencies
            self._base, self._span = 25, 55
            self.progress(26, "Installing PyTorch (the big one)")
            self._run([str(vpy), "-m", "pip", "install", "--upgrade", "pip", "-q"])
            self._run([str(vpy), "-m", "pip", "install", "torch", "torchvision",
                       "--index-url", "https://download.pytorch.org/whl/cpu", "-q"])
            self.progress(65, "Installing remaining dependencies")
            self._run([str(vpy), "-m", "pip", "install", "pillow", "pyyaml",
                       "numpy", "pandas", "opencv-python<5", "-q"])

            # 5. Weights
            self._base, self._span = 80, 15
            self.progress(81, "Downloading model")
            models = where / "models"
            models.mkdir(exist_ok=True)
            wanted = list(WEIGHTS)
            if self.include_second_model.get():
                wanted += OPTIONAL_WEIGHTS
            for w in wanted:
                self._download(f"{RELEASE}/{w}", models / w, w)

            # 6. Uninstaller, Windows only.
            #
            # It is carried inside this executable rather than downloaded. That
            # removes a network round-trip that could fail after everything
            # else succeeded, and it takes a file off the releases page that
            # was only ever confusing there - downloaded on its own it refuses
            # to do anything, because it is meant to sit in the install folder.
            #
            # macOS needs none of this. The whole application is a bundle, so
            # removing it is dragging it to the Trash.
            self.progress(94, "Finishing up")
            if IS_WINDOWS:
                try:
                    src = bundled(UNINSTALLER)
                    if src.exists():
                        shutil.copy2(src, target / UNINSTALLER)
                        self.log(f"Uninstaller placed in {target.name}")
                    else:
                        self.log("No uninstaller was bundled with this build; "
                                 "remove the folder by hand to uninstall.")
                except Exception as e:
                    self.log(f"Could not place the uninstaller: {e}")

            # 7. Shortcut. Not on macOS - the bundle is already in Applications
            #    and Mac users do not expect desktop icons.
            self.progress(96, "Finishing up")
            if self.create_shortcut.get() and not IS_MAC:
                try:
                    made = self._make_shortcut(target)
                    self.log(f"Desktop shortcut created: {made}")
                except Exception as e:
                    self.log(f"Could not create shortcut: {e}")
                    self.log(f"Launch it directly instead: {where / 'app.py'}")
            elif IS_MAC:
                self.log(f"Installed to {target}")
                # Ask Finder to notice the new bundle straight away.
                subprocess.run(["/System/Library/Frameworks/CoreServices.framework"
                                "/Frameworks/LaunchServices.framework/Support/lsregister",
                                "-f", str(target)], capture_output=True)

            self.progress(100, "Done")
            self.log("\nInstallation complete.")
            self.log_queue.put(("done", None))

        except Exception as e:
            self.log(f"\nFAILED: {e}")
            self.log_queue.put(("error", e))

    def _make_shortcut(self, target: Path) -> Path:
        """
        Create the desktop shortcut and return where it went.

        Returns the path rather than nothing, and raises if the file is not
        there afterwards. The previous version ran cscript with check=False and
        then logged success unconditionally, so it reported a shortcut it had
        not made.
        """
        desktop = desktop_dir()
        if not desktop.is_dir():
            raise RuntimeError(f"Desktop folder not found at {desktop}")

        if platform.system() == "Windows":
            vbs = target / "_shortcut.vbs"
            lnk = desktop / f"{APP_NAME}.lnk"
            icon = target / "app.ico"

            # Point at the batch launcher rather than pythonw.exe.
            #
            # pythonw runs with no window at all, and importing torch
            # still takes a few seconds before the window appears. To the user
            # that is indistinguishable from nothing happening - and if it
            # fails, it fails just as silently. The
            # launcher prints what it is doing, checks its prerequisites, and
            # leaves the error on screen instead of swallowing it.
            launcher = target / "Launch Detector.bat"
            if launcher.exists():
                tgt, args = launcher, ""
            else:
                tgt, args = target / "venv" / "Scripts" / "pythonw.exe", "app.py"

            lines = [
                'Set s = CreateObject("WScript.Shell")',
                f'Set l = s.CreateShortcut("{lnk}")',
                f'l.TargetPath = "{tgt}"',
                f'l.Arguments = "{args}"',
                f'l.WorkingDirectory = "{target}"',
                f'l.Description = "{APP_NAME}"',
            ]
            if icon.exists():
                lines.append(f'l.IconLocation = "{icon}"')
            lines += ['l.Save', '']
            vbs.write_text("\r\n".join(lines), encoding="utf-8")
            r = subprocess.run(["cscript", "//nologo", str(vbs)],
                               capture_output=True, text=True)
            vbs.unlink(missing_ok=True)
            if not lnk.exists():
                detail = (r.stderr or r.stdout or "no output").strip()
                raise RuntimeError(f"cscript did not create {lnk}: {detail}")
            return lnk
        else:
            cmd = desktop / f"{APP_NAME}.command"
            cmd.write_text(
                f'#!/bin/bash\ncd "{target}"\n'
                f'"{target}/venv/bin/python" app.py\n', encoding="utf-8")
            cmd.chmod(0o755)
            if not cmd.exists():
                raise RuntimeError(f"could not write {cmd}")
            return cmd


