# The band of Python versions this project is known to work on. The upper bound
# is not caution for its own sake: development originally started on 3.14 and
# had to be abandoned because numpy had no wheel for it and fell back to a
# source build that failed. Accepting an interpreter that new would reproduce
# that failure on the user's machine, halfway through a 700MB install, with a
# compiler error they have no way to act on. Better to detect it up front and
# install 3.11 alongside.
PY_MIN = (3, 9)
PY_MAX = (3, 13)


def _version_of(parts: list[str]) -> tuple[int, int] | None:
    """(major, minor) for the interpreter, or None if it will not run."""
    try:
        out = subprocess.run(
            [*parts, "-c",
             "import sys;print(f'{sys.version_info.major}.{sys.version_info.minor}')"],
            capture_output=True, text=True, timeout=15,
        )
        if out.returncode != 0:
            return None
        major, minor = (int(x) for x in out.stdout.strip().split("."))
        return (major, minor)
    except Exception:
        return None


def _probe(parts: list[str]) -> bool:
    v = _version_of(parts)
    return v is not None and PY_MIN <= v <= PY_MAX


def find_python() -> str | None:
    """
    Locate a usable Python, preferring newer versions within the tested band.

    Searches PATH first, then a handful of absolute locations. The absolute
    paths matter more than they look: when this installer installs Python
    itself, the new PATH entry does not exist in the already-running process,
    so a PATH-only search would fail immediately after a successful install.
    """
    windows = platform.system() == "Windows"
    on_path = (["py -3.13", "py -3.12", "py -3.11", "py -3.10", "py -3", "python"]
               if windows else
               ["python3.13", "python3.12", "python3.11", "python3.10", "python3"])

    for cand in on_path:
        parts = cand.split()
        exe = shutil.which(parts[0])
        if exe and _probe([exe, *parts[1:]]):
            return cand

    # Fixed locations, checked after PATH so a user's preferred Python wins.
    fixed: list[Path] = []
    if windows:
        fixed.append(Path(os.environ.get("WINDIR", r"C:\Windows")) / "py.exe")
        programs = Path(os.environ.get("LOCALAPPDATA", Path.home())) / "Programs" / "Python"
        for v in ("313", "312", "311", "310"):
            fixed.append(programs / f"Python{v}" / "python.exe")
            fixed.append(Path(f"C:/Python{v}/python.exe"))
    else:
        fw = Path("/Library/Frameworks/Python.framework/Versions")
        for v in ("3.13", "3.12", "3.11", "3.10"):
            fixed.append(fw / v / "bin" / f"python{v}")
        fixed += [Path("/usr/local/bin/python3"), Path("/opt/homebrew/bin/python3")]

    for p in fixed:
        if p.exists() and _probe([str(p)]):
            return str(p)
    return None


def newest_untested_python() -> tuple[int, int] | None:
    """
    Version of a Python that exists but sits outside the tested band.

    Only used to word the message. Telling someone with Python 3.14 installed
    that "no Python was found" would be both wrong and infuriating.
    """
    cands = ["py -3", "python"] if platform.system() == "Windows" else ["python3"]
    best = None
    for cand in cands:
        parts = cand.split()
        exe = shutil.which(parts[0])
        if not exe:
            continue
        v = _version_of([exe, *parts[1:]])
        if v and not (PY_MIN <= v <= PY_MAX):
            best = v if best is None or v > best else best
    return best


def python_argv(cmd: str) -> list[str]:
    """
    Turn a stored Python command into an argv list.

    find_python() returns either a PATH-style command ("py -3.11", "python3")
    or an absolute path. Splitting on whitespace is right for the first and
    wrong for the second, since a home directory can contain spaces.
    """
    if Path(cmd).exists():
        return [cmd]
    parts = cmd.split()
    return [shutil.which(parts[0]) or parts[0], *parts[1:]]


# --- Installing Python when the user does not have it ----------------------
# The compiled installer carries its own Python runtime, but that runtime is
# frozen inside the executable and cannot create a virtual environment or run
# pip. A real interpreter on the machine is still needed, so if none is found
# the installer fetches the official one from python.org rather than sending
# the user away to do it themselves.

# 3.11.9, the same version the whole project was developed and tested on.
#
# Newer lines were considered. 3.11.9 (April 2024) was the last 3.11 release to
# ship a binary installer - the line is security-only now - so this does hand
# the user a somewhat dated interpreter. The alternative, 3.13, is still
# getting maintenance releases, but nothing in this project has ever been run
# on it. Every dependency here almost certainly publishes cp313 wheels; "almost
# certainly" is not the same as tested, and a marker hitting a wheel resolution
# failure during installation is a worse outcome than an older interpreter.
# Matching the development environment removes that risk entirely.
PY_VERSION = "3.11.9"

# Published on the python.org release page alongside the downloads.
#
# MD5, not SHA-256, because MD5 is all python.org lists for 3.11.9 - the
# release pages only started publishing SHA-256 for later versions. This is
# therefore a CORRUPTION check, not a tamper check: MD5 is collision-broken and
# should not be relied on to prove the file has not been altered. It still
# catches the failure that actually happens, which is a truncated or damaged
# download being executed.
PY_MD5 = {
    f"python-{PY_VERSION}-amd64.exe":   "e8dcd502e34932eebcaf1be056d5cbcd",
    f"python-{PY_VERSION}-arm64.exe":   "328d93f71cb078965e4cfa2eb2663fa1",
    f"python-{PY_VERSION}-macos11.pkg": "fa29f456feb6b5c4f52456a8b8ba347b",
}


def python_installer_url() -> tuple[str, str]:
    """(url, filename) for the official python.org installer for this machine."""
    base = f"https://www.python.org/ftp/python/{PY_VERSION}"
    if platform.system() == "Windows":
        arch = "arm64" if platform.machine().lower() in ("arm64", "aarch64") else "amd64"
        name = f"python-{PY_VERSION}-{arch}.exe"
    else:
        # The universal2 package covers both Intel and Apple Silicon.
        name = f"python-{PY_VERSION}-macos11.pkg"
    return f"{base}/{name}", name


def md5_of(path: Path) -> str:
    # usedforsecurity=False says plainly what this is for, and keeps the call
    # working on systems running Python in FIPS mode, where plain md5() raises.
    try:
        h = hashlib.md5(usedforsecurity=False)
    except TypeError:          # the keyword arrived in 3.9
        h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


