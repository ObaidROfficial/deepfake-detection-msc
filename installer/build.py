"""
Compile the installer and uninstaller into standalone executables.

Build with the BASE Python install rather than the project venv:

    py -3.11 -m pip install pyinstaller
    py -3.11 installer/build.py

The venv is deliberately avoided. Windows virtual environments do not copy the
tcl/tk runtime, and PyInstaller occasionally fails to locate it when freezing a
tkinter app from inside one. The base install has tkinter set up properly and
none of the heavy project dependencies, so the bundle stays small without
relying on the exclude list below.

    --console   keep the console window so tracebacks are visible. Build this
                first and test with it; a --noconsole build that dies on
                startup shows the user nothing at all.
    --only X    build just "setup" or just "uninstall".

Run this on each platform you want to support - PyInstaller cannot
cross-compile, so a Windows .exe must be built on Windows and a macOS binary on
macOS. Output lands in installer/dist/, which is gitignored; the executables go
on a GitHub release rather than into the repository.

WHY THE BUNDLE IS SMALL
Only the installer is compiled, and it imports nothing beyond tkinter and the
standard library. PyTorch, Gradio and the rest are downloaded at install time
into a virtual environment on the user's machine. Bundling them instead would
push each download past a gigabyte and make the build fragile.

A NOTE ON CODE SIGNING
These executables are unsigned. On Windows, SmartScreen will show "Windows
protected your PC" and the user must click More info -> Run anyway. On macOS,
Gatekeeper refuses to open them on a double-click; the user must right-click and
choose Open, then confirm. Signing requires a paid certificate from Microsoft or
Apple. This is documented for the user in installer/README.md rather than left
as a surprise.
"""

from __future__ import annotations

import argparse
import platform
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
APP_NAME = "OBI-DeepFake-Image-Detector"

# PyInstaller's scratch space, deliberately outside the project folder.
#
# Building inside a OneDrive-synced directory fails in two ways. The sync client
# takes handles on files while PyInstaller is still writing them, and anything
# produced by an elevated build cannot afterwards be deleted by a normal one -
# which surfaces as "Access is denied: ...\\localpycs" when --clean runs.
# Neither has anything to do with the build itself, so the work happens in the
# system temp directory. Only the finished executables land in the repository.
WORK = Path(tempfile.gettempdir()) / "obi-detector-build"

TARGETS = {
    "setup":     ("installer.py",   f"{APP_NAME}-Setup"),
    "uninstall": ("uninstaller.py", f"{APP_NAME}-Uninstall"),
}

EXCLUDES = [
    "torch", "torchvision", "numpy", "pandas", "matplotlib",
    "cv2", "gradio", "PIL", "scipy", "sklearn", "skimage",
    "IPython", "jupyter", "notebook",
]


def icon_file() -> Path | None:
    """The platform's icon, if one has been generated by make_icon.py."""
    name = "app.icns" if platform.system() == "Darwin" else "app.ico"
    p = HERE / name
    return p if p.exists() else None


def check_pyinstaller() -> bool:
    try:
        import PyInstaller  # noqa: F401
        return True
    except ImportError:
        print("PyInstaller is not available to this interpreter.\n")
        print(f"  interpreter: {sys.executable}")
        print(f"  install it:  \"{sys.executable}\" -m pip install pyinstaller\n")
        return False


def check_tkinter() -> bool:
    try:
        import tkinter  # noqa: F401
        return True
    except ImportError:
        print("This interpreter has no tkinter, so the installer cannot be frozen.")
        print("Use the python.org build rather than a stripped-down one.\n")
        return False


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--console", action="store_true",
                    help="keep the console window (build this first, for testing)")
    ap.add_argument("--only", choices=sorted(TARGETS),
                    help="build only one of the two executables")
    args = ap.parse_args()

    if not check_pyinstaller() or not check_tkinter():
        return 1

    system = platform.system()
    print(f"Building on {system} ({platform.machine()})")
    print(f"Python {sys.version.split()[0]} at {sys.executable}")
    print(f"Mode: {'console (debug)' if args.console else 'windowed (release)'}")
    ic = icon_file()
    print("Icon: " + (str(ic.name) if ic else
                      "none yet - run make_icon.py to add one"))
    print(f"Scratch: {WORK}")

    # Left over from when the work directory lived in the repo. Harmless, but
    # it sits inside OneDrive being synced for no reason.
    stale = HERE / "build"
    if stale.exists():
        try:
            shutil.rmtree(stale)
            print(f"Removed stale {stale}")
        except Exception:
            print(f"Note: {stale} is left over and can be deleted by hand"
                  f" (it may need admin, if an elevated build created it).")
    print()

    wanted = [args.only] if args.only else list(TARGETS)
    built: list[Path] = []

    for key in wanted:
        script, base = TARGETS[key]
        name = base + ("-debug" if args.console else "")
        src = HERE / script
        if not src.exists():
            print(f"  missing: {src}")
            return 1

        cmd = [
            sys.executable, "-m", "PyInstaller",
            "--onefile",
            "--console" if args.console else "--noconsole",
            "--clean",
            "--noconfirm",
            "--name", name,
            "--distpath", str(HERE / "dist"),
            "--workpath", str(WORK / "work"),
            "--specpath", str(WORK / "spec"),
            # picked up automatically, but missed on some minimal installs
            "--hidden-import", "tkinter",
            "--hidden-import", "tkinter.filedialog",
            "--hidden-import", "tkinter.messagebox",
            "--hidden-import", "tkinter.ttk",
        ]

        # Icon, if one has been made. Two separate things are needed: --icon
        # sets the image Explorer shows for the .exe, while --add-data puts a
        # copy inside the bundle so the window itself can display it too.
        icon = icon_file()
        if icon:
            sep = ";" if platform.system() == "Windows" else ":"
            cmd += ["--icon", str(icon), "--add-data", f"{icon}{sep}."]

        for mod in EXCLUDES:
            cmd += ["--exclude-module", mod]
        cmd.append(str(src))

        # A previous run's .exe stays locked while it is open, and PyInstaller
        # reports that as a generic failure at the very end of a long build.
        out = HERE / "dist" / (name + (".exe" if system == "Windows" else ""))
        if out.exists():
            try:
                out.unlink()
            except PermissionError:
                print(f"  {out.name} is locked - close it and run this again.")
                return 1

        print(f"Building {name} ...")
        if subprocess.run(cmd).returncode != 0:
            print(f"  FAILED: {name}")
            print("  If this was an access-denied error, something is holding")
            print(f"  a file open. Scratch space is {WORK}")
            return 1

        for p in sorted((HERE / "dist").glob(f"{name}*")):
            if p.is_file():
                built.append(p)
                print(f"  built  {p.name}  ({p.stat().st_size/1e6:.1f} MB)")
            elif p.suffix == ".app":
                # macOS windowed builds also emit a .app. PyInstaller itself
                # warns that this combination clashes with Gatekeeper, and the
                # plain binary is what gets published, so say so rather than
                # leaving an unexplained bundle in dist/.
                print(f"  also   {p.name}  (macOS bundle - not the artefact "
                      f"to publish)")

    print("\nOutput in", HERE / "dist")
    for p in built:
        print("   ", p)

    if args.console:
        print("\nThis is the DEBUG build. Run it from a terminal, reproduce the")
        print("problem, and read the traceback. When it behaves, rebuild without")
        print("--console for the version you ship.")
    else:
        print("\nBefore publishing, test on a machine that has never had this")
        print("project installed. That is the only way to catch a dependency the")
        print("build environment happened to provide.")
        if system == "Darwin":
            arch = platform.machine()
            print(f"\nThis build is {arch} ONLY. PyInstaller targets the")
            print("architecture it runs on, so an Intel Mac needs its own build")
            print("(or install from source with setup.sh instead).")
            print("\nPublish the Setup binary zipped - a bare Unix executable")
            print("loses its execute bit when downloaded through a browser:")
            print(f"    cd {HERE / 'dist'}")
            print(f"    zip OBI-DeepFake-Image-Detector-Setup-macOS-{arch}.zip \\")
            print("        OBI-DeepFake-Image-Detector-Setup")
            print("\nPublish the Uninstall binary BARE, under exactly that")
            print("name - installer.py fetches it by name and chmods it itself.")
            print("\nWhoever downloads Setup will still need right-click ->")
            print("Open the first time; Gatekeeper blocks unsigned binaries on")
            print("a double-click.")
        elif system == "Windows":
            print("\nWindows: SmartScreen warns on first run.")
            print("Users click More info -> Run anyway.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
